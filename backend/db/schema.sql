-- Hakiki Oracle Autonomous Database schema.
-- Apply once with the application schema user before DB_BACKEND=oracle.
-- Claim JSON is synthetic demo data only. Never insert real patient data.

CREATE TABLE claims (
    id              VARCHAR2(128) PRIMARY KEY,
    claim_ref       VARCHAR2(32) NOT NULL UNIQUE,
    facility        VARCHAR2(255),
    department      VARCHAR2(64),
    payload         CLOB NOT NULL CHECK (payload IS JSON),
    status          VARCHAR2(64),
    current_version NUMBER(10) DEFAULT 1 NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE claim_versions (
    claim_id   VARCHAR2(128) NOT NULL REFERENCES claims(id),
    version    NUMBER(10) NOT NULL,
    payload    CLOB NOT NULL CHECK (payload IS JSON),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    created_by VARCHAR2(120),
    version_fingerprint CHAR(64) NOT NULL,
    event_seq NUMBER(20),
    changed_fields_json CLOB CHECK (changed_fields_json IS JSON),
    CONSTRAINT claim_versions_pk PRIMARY KEY (claim_id, version)
);

CREATE TABLE validation_runs (
    id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_id      VARCHAR2(128) NOT NULL REFERENCES claims(id),
    version       NUMBER(10),
    score         NUMBER(3) NOT NULL,
    status        VARCHAR2(64) NOT NULL,
    error_count   NUMBER(5) DEFAULT 0 NOT NULL,
    warning_count NUMBER(5) DEFAULT 0 NOT NULL,
    counts_json   CLOB CHECK (counts_json IS JSON),
    ledger_seq    NUMBER(20),
    created_at    TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    rules_version VARCHAR2(64) DEFAULT 'unknown' NOT NULL,
    rules_date    VARCHAR2(10) DEFAULT 'unknown' NOT NULL,
    informational NUMBER(1) DEFAULT 0 NOT NULL
);

CREATE TABLE department_signoffs (
    claim_id    VARCHAR2(128) NOT NULL REFERENCES claims(id),
    department  VARCHAR2(64) NOT NULL,
    status      VARCHAR2(32) NOT NULL,
    note        VARCHAR2(2000),
    signed_by   VARCHAR2(120),
    signed_at   TIMESTAMP WITH TIME ZONE,
    review_json CLOB NOT NULL CHECK (review_json IS JSON),
    updated_at  TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT department_signoffs_pk PRIMARY KEY (claim_id, department)
);

CREATE TABLE claim_outcomes (
    id          VARCHAR2(64) PRIMARY KEY,
    claim_id    VARCHAR2(128) NOT NULL REFERENCES claims(id),
    department  VARCHAR2(64),
    outcome     VARCHAR2(32) NOT NULL,
    reason      VARCHAR2(120),
    note        VARCHAR2(2000),
    recorded_at TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Store commitments and random references only; never claim IDs, names,
-- phone numbers, notes, or raw event payloads in this table.
CREATE TABLE audit_ledger (
    seq           NUMBER(20) PRIMARY KEY,
    claim_ref     VARCHAR2(32),
    event_type    VARCHAR2(64) NOT NULL,
    payload_hash  CHAR(64) NOT NULL,
    prev_hash     CHAR(64) NOT NULL,
    hash          CHAR(64) NOT NULL UNIQUE,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    anchored_tx   VARCHAR2(80),
    chain_version NUMBER(2) DEFAULT 4 NOT NULL
);

CREATE TABLE anchors (
    id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    from_seq   NUMBER(20) NOT NULL,
    to_seq     NUMBER(20) NOT NULL,
    root_hash  CHAR(66) NOT NULL,
    tx_hash    VARCHAR2(80) UNIQUE,
    status     VARCHAR2(16) DEFAULT 'confirmed' NOT NULL,
    head_hash  CHAR(64),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT anchors_range_ck CHECK (from_seq > 0 AND to_seq >= from_seq),
    CONSTRAINT anchors_status_ck CHECK (status IN ('pending', 'confirmed', 'failed')),
    CONSTRAINT anchors_root_hash_uq UNIQUE (root_hash)
);

-- Checkpoint written only after a successful full-ledger verification.
CREATE TABLE audit_verification_checkpoint (
    singleton_id      NUMBER(1) PRIMARY KEY CHECK (singleton_id = 1),
    last_verified_seq NUMBER(20) NOT NULL,
    last_verified_hash CHAR(64) NOT NULL,
    verified_at       TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE legacy_anchors (
    source_seq NUMBER(20) PRIMARY KEY,
    from_seq   NUMBER(20) NOT NULL,
    to_seq     NUMBER(20) NOT NULL,
    root_hash  CHAR(66),
    tx_hash    VARCHAR2(80),
    source_hash CHAR(64) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE
);

-- Serialize appends with SELECT ... FOR UPDATE on this singleton row.
CREATE TABLE audit_ledger_head (
    singleton_id NUMBER(1) PRIMARY KEY CHECK (singleton_id = 1),
    last_seq     NUMBER(20) NOT NULL,
    last_hash    CHAR(64) NOT NULL
);

CREATE TABLE audit_event_details (
    event_seq   NUMBER(20) PRIMARY KEY REFERENCES audit_ledger(seq),
    details_json CLOB NOT NULL CHECK (details_json IS JSON)
);

CREATE INDEX validation_runs_claim_idx ON validation_runs(claim_id, created_at);
CREATE INDEX audit_ledger_ref_idx ON audit_ledger(claim_ref, seq);
